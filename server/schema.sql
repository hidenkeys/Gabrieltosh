CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN ('admin','supervisor','cashier')), active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),expires_at TIMESTAMPTZ NOT NULL);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY,value JSONB NOT NULL);
CREATE TABLE IF NOT EXISTS products (
 id TEXT PRIMARY KEY, code TEXT NOT NULL, name TEXT NOT NULL, category TEXT NOT NULL, price INTEGER NOT NULL CHECK(price>=0),
 size TEXT NOT NULL DEFAULT '', available BOOLEAN NOT NULL DEFAULT true,label_required BOOLEAN NOT NULL DEFAULT true,
 options BOOLEAN NOT NULL DEFAULT true, needs_review BOOLEAN NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS orders (
 id TEXT PRIMARY KEY, number SERIAL UNIQUE, status TEXT NOT NULL DEFAULT 'pending', payment_status TEXT NOT NULL DEFAULT 'unpaid',
 staff_id TEXT NOT NULL REFERENCES users(id), staff_name TEXT NOT NULL, items JSONB NOT NULL, subtotal INTEGER NOT NULL,
 discount INTEGER NOT NULL DEFAULT 0,discount_reason TEXT NOT NULL DEFAULT '',total INTEGER NOT NULL,
 note TEXT NOT NULL DEFAULT '',payment_method TEXT,paid_by TEXT REFERENCES users(id),paid_by_name TEXT,
 cash_tendered INTEGER,paid_at TIMESTAMPTZ,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, version INTEGER NOT NULL DEFAULT 1,
 request_key TEXT UNIQUE NOT NULL,refund_amount INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS print_jobs (
 id TEXT PRIMARY KEY,order_id TEXT NOT NULL REFERENCES orders(id),kind TEXT NOT NULL CHECK(kind IN ('receipt','label')),
 sequence INTEGER NOT NULL,payload JSONB NOT NULL,status TEXT NOT NULL DEFAULT 'queued', attempts INTEGER NOT NULL DEFAULT 0,
 error TEXT,lease_at TIMESTAMPTZ,completed_at TIMESTAMPTZ,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reprint BOOLEAN NOT NULL DEFAULT false,simulated BOOLEAN NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS audit (
 id TEXT PRIMARY KEY,user_id TEXT,user_name TEXT NOT NULL,action TEXT NOT NULL,order_id TEXT,
 details JSONB NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS closures (
 id TEXT PRIMARY KEY,business_date TEXT UNIQUE NOT NULL,report JSONB NOT NULL,counted_cash INTEGER NOT NULL,
 expected_cash INTEGER NOT NULL,variance INTEGER NOT NULL,closed_by TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS refunds (
 id TEXT PRIMARY KEY,order_id TEXT NOT NULL REFERENCES orders(id),amount INTEGER NOT NULL,method TEXT NOT NULL,
 reason TEXT NOT NULL,staff_name TEXT NOT NULL,created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS backup_runs (
 id TEXT PRIMARY KEY,status TEXT NOT NULL,path TEXT,error TEXT,cloud_status TEXT NOT NULL DEFAULT 'pending',
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS orders_created_idx ON orders(created_at);
CREATE INDEX IF NOT EXISTS jobs_status_idx ON print_jobs(status);
CREATE INDEX IF NOT EXISTS audit_created_idx ON audit(created_at);
